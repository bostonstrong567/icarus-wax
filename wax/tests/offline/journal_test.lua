t.test("the entries of one row are found by the start of their keys, and what is on its way out or owed is listed", function()
    local first = journal.open("recipes\0axe\0Inputs", "recipes", {}, 1)
    local second = journal.open("recipes\0axe\0Work", "recipes", {}, 1)
    local third = journal.open("recipes\0axe_long\0Work", "recipes", {}, 1)
    local other = journal.open("items\0axe\0Work", "items", {}, 1)
    local found = journal.under("recipes", "recipes\0axe\0")
    t.eq(#found, 2, "the two fields of Axe, and not those of a row whose name begins the same")
    t.ok((found[1] == first and found[2] == second) or (found[1] == second and found[2] == first))
    t.eq(#journal.under("nothing", "recipes\0axe\0"), 0)
    journal.push(first, "A", { set = 2 }, rank)
    journal.push(second, "A", { set = 2 }, rank)
    journal.push(third, "B", { set = 2 }, rank)
    t.eq(#journal.pending(), 0, "nothing is leaving")
    journal.leave("B")
    other.owed = true
    t.eq(table.concat(journal.pending(), ","), "items\0axe\0Work,recipes\0axe_long\0Work", "sorted: a leaving layer, and a put-back that is owed")
    t.eq(table.concat(journal.owners(), ","), "A,B")
    local row = journal.add_row("recipes\0c_axe", { group = "recipes", table = "Recipes", row = "C_Axe", owner = "C" })
    t.eq(table.concat(journal.owners(), ","), "A,B,C", "a mod that only added a row has something standing too")
    row.retired = true
    t.eq(table.concat(journal.owners(), ","), "A,B", "but not once the row is switched off")
    journal.remove_row("recipes\0c_axe")
    for _, entry in ipairs({ first, second, third, other }) do journal.close(entry) end
end)

t.test("the names of enums are kept where the journal is, so another core finds them", function()
    local enums = journal.enums()
    t.eq(journal.enums(), enums, "one table")
    enums["/Script/Icarus.Recipe:Mode"] = { names = { "Slow" } }
    local other = t.new_wax().import("data.journal")
    t.eq(other.enums()["/Script/Icarus.Recipe:Mode"].names[1], "Slow")
    enums["/Script/Icarus.Recipe:Mode"] = nil
end)

t.test("the journal outlives the core: another core finds it, and what mods changed in it is leaving", function()
    local entry = fresh("kept", 1)
    journal.push(entry, "A", { set = 2 }, rank)
    journal.push(entry, "B", { set = 3 }, rank)
    -- a row that was switched off: the layer that does it belongs to no mod
    local off = fresh("off", false)
    journal.push(off, "(off)", { set = true }).layer.quiet = true
    off.applied = true
    local row = journal.add_row("recipes\0a_axe", { group = "recipes", table = "Recipes", row = "A_Axe", owner = "A" })
    local keys = journal.adopt(Wax)
    t.eq(#keys, 0, "the first core to come takes it as it is")
    t.eq(owners(entry), "A,B")
    t.eq(#(journal.adopt(Wax)), 0, "the same core again: nothing happens")
    local second = t.new_wax()
    local again = second.import("data.journal")
    t.ok(again ~= journal, "another module in another core")
    t.eq(again.find("kept"), entry, "with the same entries")
    t.eq(again.count("recipes"), 2, "and the same counts")
    local rows
    keys, rows = again.adopt(second)
    t.eq(table.concat(keys, ","), "kept,off", "every key is looked at")
    t.eq(#rows, 1)
    t.eq(owners(entry), "A?,B?", "the mods of the core before are gone")
    t.eq(owners(off), "(off)", "the layer that switches a row off is not leaving")
    t.eq(off.applied, nil, "and its field is read from the game again, in case the game no longer holds it")
    t.eq(result(off), true)
    t.eq(row.leaving, true)
    again.push(entry, "A", { set = 2 }, rank)
    t.eq(owners(entry), "A,B?", "a mod that loads again in the new core takes its place back")
    again.remove_row("recipes\0a_axe")
    again.close(entry)
    again.close(off)
end)

t.test("clear forgets everything but the names of enums, which hold while the game runs", function()
    local entry = fresh("temp", 1)
    journal.push(entry, "A", { set = 2 }, rank)
    journal.enums()["/Script/Icarus.Recipe:Mode"] = { names = { "Slow" } }
    journal.clear()
    t.eq(journal.enums()["/Script/Icarus.Recipe:Mode"].names[1], "Slow")
    journal.enums()["/Script/Icarus.Recipe:Mode"] = nil
    t.eq(journal.find("temp"), nil)
    local stats = journal.stats()
    t.eq(stats.entries + stats.layers + stats.rows + stats.owners + stats.tables, 0)
    t.eq(journal.count("recipes"), 0)
    t.eq(journal.first("A and B on Axe"), true, "what was said is forgotten too")
end)

